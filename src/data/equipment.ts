export function getEquipmentBySlug(slug: string): Equipment | undefined {
  return equipmentListings.find((e) => e.slug === slug);
}

export function getFeaturedEquipment(): Equipment[] {
  return equipmentListings.filter((e) => e.featured);
}

export function getEquipmentByCategory(categorySlug: string): Equipment[] {
  return equipmentListings.filter((e) => e.categorySlug === categorySlug);
}

export function getEquipmentByBrand(brand: string): Equipment[] {
  return equipmentListings.filter((e) => e.brand.toLowerCase() === brand.toLowerCase());
}

export function getSimilarEquipment(equipment: Equipment, limit: number = 4): Equipment[] {
  return equipmentListings
    .filter((e) => e.id !== equipment.id && (e.categorySlug === equipment.categorySlug || e.brand === equipment.brand))
    .slice(0, limit);
}
